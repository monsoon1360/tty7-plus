#!/usr/bin/env python3
"""Generate Compose vectors from the desktop's monochrome Agent SVGs."""
from pathlib import Path
import json
import re
import xml.etree.ElementTree as ET

root = Path(__file__).resolve().parents[2]
output = root / 'mobile/app/src/commonMain/kotlin/io/tty7/mobile/AgentMarks.kt'
lines = ['// Generated by mobile/scripts/generate-agent-marks.py from assets/icons/agents.',
         'package io.tty7.mobile', '',
         'import androidx.compose.ui.graphics.Color',
         'import androidx.compose.ui.graphics.PathFillType',
         'import androidx.compose.ui.graphics.SolidColor',
         'import androidx.compose.ui.graphics.vector.ImageVector',
         'import androidx.compose.ui.graphics.vector.PathParser',
         'import androidx.compose.ui.unit.dp', '',
         'internal fun agentMark(kind: String): ImageVector? = when (kind) {']
files = sorted((root / 'assets/icons/agents').glob('*.svg'))
for file in files:
    lines.append(f'    "{file.stem}" -> mark_{file.stem}')
lines += ['    else -> null', '}', '']

def emit(element, depth=1):
    tag = element.tag.split('}')[-1]
    if tag in ('defs', 'style', 'clipPath'):
        return
    attrs = element.attrib
    indent = '    ' * depth
    if tag in ('svg', 'g'):
        transform = attrs.get('transform', '')
        if transform:
            match = re.fullmatch(r'(scale|translate)\(([^)]+)\)', transform)
            if not match:
                raise ValueError(transform)
            nums = [float(n) for n in re.split(r'[, ]+', match[2])]
            x, y = nums[0], nums[1] if len(nums) > 1 else (nums[0] if match[1] == 'scale' else 0)
            fields = f'scaleX = {x}f, scaleY = {y}f' if match[1] == 'scale' else f'translationX = {x}f, translationY = {y}f'
            lines.append(f'{indent}pushGroup({fields})')
        for child in element:
            emit(child, depth)
        if transform:
            lines.append(f'{indent}popGroup()')
        return
    if tag == 'path':
        path = attrs['d']
    elif tag == 'rect':
        x, y, w, h = [float(attrs.get(k, 0)) for k in ('x', 'y', 'width', 'height')]
        rx = min(float(attrs.get('rx', attrs.get('ry', 0))), w / 2)
        ry = min(float(attrs.get('ry', attrs.get('rx', 0))), h / 2)
        if rx and ry:
            path = f'M{x+rx},{y}H{x+w-rx}A{rx},{ry} 0 0 1 {x+w},{y+ry}V{y+h-ry}A{rx},{ry} 0 0 1 {x+w-rx},{y+h}H{x+rx}A{rx},{ry} 0 0 1 {x},{y+h-ry}V{y+ry}A{rx},{ry} 0 0 1 {x+rx},{y}Z'
        else:
            path = f'M{x},{y}h{w}v{h}h{-w}Z'
    else:
        raise ValueError(f'Unsupported SVG element: {tag}')
    fill = 'EvenOdd' if attrs.get('fill-rule') == 'evenodd' else 'NonZero'
    lines.append(f'{indent}addPath(pathData = PathParser().parsePathString({json.dumps(path)}).toNodes(), fill = SolidColor(Color.White), pathFillType = PathFillType.{fill})')

for file in files:
    svg = ET.parse(file).getroot()
    x, y, w, h = [float(n) for n in svg.attrib['viewBox'].split()]
    assert x == y == 0
    lines.append(f'private val mark_{file.stem}: ImageVector by lazy {{')
    lines.append(f'    ImageVector.Builder(name = "{file.stem}", defaultWidth = 24.dp, defaultHeight = 24.dp, viewportWidth = {w}f, viewportHeight = {h}f).apply {{')
    emit(svg, 2)
    lines += ['    }.build()', '}', '']
output.write_text('\n'.join(lines))
